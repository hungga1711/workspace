#!/usr/bin/env node
// Generates docs/events/catalog.md from the event registry in @workspace/contracts and checks the
// code agrees with it:
//   - every event type written in backend code is registered,
//   - every registered event is produced somewhere (the ops probe excepted),
//   - every "projection" event is read somewhere ("audit" events may have no reader).
//
//   node tooling/scripts/events-catalog.mjs          rewrite the catalog
//   node tooling/scripts/events-catalog.mjs --check  fail if it is stale or a rule is broken (CI)
//
// Needs the built contracts package (pnpm build:packages).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const { EVENTS, describePayload } = await import(join(root, "backend/packages/contracts/dist/index.js"));
const out = join(root, "docs/events/catalog.md");
const check = process.argv.includes("--check");

function* sources(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== "node_modules" && e.name !== "dist" && e.name !== "test") yield* sources(p);
    } else if (e.name.endsWith(".ts") && !e.name.endsWith(".test.ts") && !e.name.endsWith(".d.ts")) yield p;
  }
}
const files = [...sources(join(root, "backend/server/src"))];
for (const pkg of readdirSync(join(root, "backend/packages"))) {
  if (pkg === "contracts") continue; // the registry itself
  try {
    for (const f of sources(join(root, "backend/packages", pkg, "src"))) files.push(f);
  } catch {
    /* no src */
  }
}

const TYPE = /["'`]([a-z]+(?:\.[a-z_]+)+\.v\d+)["'`]/g;
const producers = new Map();
const readers = new Map();
const webhooks = new Set();
const unknown = new Map();
const add = (m, k, v) => m.set(k, new Set([...(m.get(k) ?? []), v]));

for (const f of files) {
  const rel = relative(join(root, "backend"), f).replace(/^server\/src\//, "");
  // The re-index feeds replay current rows as events; they are neither producers nor consumers.
  if (rel.endsWith("search-feed.ts")) continue;
  const lines = readFileSync(f, "utf8").split("\n");
  lines.forEach((line, i) => {
    for (const [, type] of line.matchAll(TYPE)) {
      if (!EVENTS[type]) {
        add(unknown, type, `${rel}:${i + 1}`);
        continue;
      }
      if (rel === "modules/platform/webhooks.ts") webhooks.add(type);
      else if (/emit\(|eventType:\s*["'`]/.test(line)) add(producers, type, rel);
      else if (/case\s+["'`]|eventType\s*[!=]==|payloadOf\(/.test(line)) add(readers, type, rel);
    }
    // Producers that build the type from a template (`ai.connection.${action}.v1`).
    for (const [, prefix] of line.matchAll(/`([a-z]+\.[a-z_]+)\.\$\{/g)) {
      for (const type of Object.keys(EVENTS)) if (type.startsWith(`${prefix}.`) && /eventType/.test(line)) add(producers, type, rel);
    }
  });
}

const problems = [];
for (const [type, at] of unknown) problems.push(`${type} is used in ${[...at].join(", ")} but not registered in backend/packages/contracts/src/events`);
for (const [type, def] of Object.entries(EVENTS)) {
  if (!producers.has(type) && def.aggregateType !== "ops.probe") problems.push(`${type} is registered but nothing produces it`);
  if (def.intent === "projection" && !readers.has(type) && !webhooks.has(type))
    problems.push(`${type} is a projection event but nothing reads it (mark it "audit" if that is intended)`);
}

const byTopic = new Map();
for (const [type, def] of Object.entries(EVENTS)) add(byTopic, `workspace.${def.aggregateType}`, type);
const domains = [...new Set([...byTopic.keys()].map((t) => t.split(".")[1]))];
const title = (d) => ({ ai: "AI", ops: "Operations" })[d] ?? d[0].toUpperCase() + d.slice(1);
const list = (s) =>
  s?.size
    ? [...s]
        .sort()
        .map((x) => `\`${x}\``)
        .join("<br>")
    : "none";

let md = `# Event catalog

<!-- Generated by tooling/scripts/events-catalog.mjs from backend/packages/contracts/src/events. Do not edit by hand. -->

Every event type a module may publish, grouped by topic (\`workspace.<aggregateType>\`). The registry
in [\`@workspace/contracts\`](../../backend/packages/contracts/src/events/registry.ts) is the source of truth:
\`appendToOutbox\` refuses an unregistered type or a payload that does not match its schema, and every
consumer validates payloads before handling them. How events flow: [README.md](README.md).

- **Intent**: *projection* events drive another module's data (Home, search, chat onboarding...);
  *audit* events are published for the record and for integrations and may have no reader here.
- **Produced in / Read in**: source files under \`backend/server/src/\` that write or
  handle the type by name. **Webhook** marks the types a workspace can subscribe to
  (\`modules/platform/webhooks.ts\`).
- Payload fields: \`?\` optional; timestamps travel as ISO strings.

Regenerate after changing the registry or the code that produces/reads events:
\`pnpm build:packages && node tooling/scripts/events-catalog.mjs\` (CI runs it with \`--check\`).
`;

for (const d of domains) {
  md += `\n## ${title(d)}\n`;
  for (const topic of [...byTopic.keys()].filter((t) => t.split(".")[1] === d).sort()) {
    md += `\n### \`${topic}\`\n\n| Event | What happened | Payload | Intent | Produced in | Read in |\n|---|---|---|---|---|---|\n`;
    for (const type of [...byTopic.get(topic)].sort()) {
      const def = EVENTS[type];
      const payload = describePayload(def.payload)
        .map((f) => `\`${f}\``)
        .join("<br>");
      md += `| \`${type}\`${webhooks.has(type) ? "<br>Webhook" : ""} | ${def.summary} | ${payload} | ${def.intent} | ${list(producers.get(type))} | ${list(readers.get(type))} |\n`;
    }
  }
}
md += `\n${Object.keys(EVENTS).length} event types on ${byTopic.size} topics.\n`;

if (problems.length) {
  console.error(`Event catalog problems:\n- ${problems.join("\n- ")}`);
  process.exit(1);
}
if (check) {
  const current = readFileSync(out, "utf8");
  if (current !== md) {
    console.error("docs/events/catalog.md is out of date: run `pnpm build:packages && node tooling/scripts/events-catalog.mjs` and commit the result.");
    process.exit(1);
  }
  console.log("Event catalog is up to date.");
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${relative(root, out)} (${Object.keys(EVENTS).length} event types).`);
}
